/// The semitones type is a number representing semitones, used for chromatic alteration. A value of -1
/// corresponds to a flat and a value of 1 to a sharp. Decimal values like 0.5 (quarter tone sharp) are used for
/// microtones.
public typealias MXLSemitones = Double
